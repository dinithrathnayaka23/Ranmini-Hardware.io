"use server";

import { revalidatePath } from "next/cache";

import { apiFetch } from "@/shared/lib/api.server";
import { routes } from "@/shared/config/app.config";
import { ApiError, errorMessages } from "@/shared/lib/http-error";

import type { CheckoutResult, CompletedSale, TenderMethod } from "./types/pos.types";

/**
 * Completing a sale, from the till.
 *
 * <p>A Server Action rather than a route handler the browser calls directly.
 * The session token lives in an httpOnly cookie that client JavaScript cannot
 * read, so the request to the backend has to be made on the server — and an
 * action keeps that fact from turning into a hand-written BFF endpoint per
 * mutation.
 *
 * <p><b>Notice what is not sent: money.</b> Only product ids and quantities. The
 * backend recomputes every amount from the catalogue and the shop's tax
 * settings, because a total posted by a browser is a number the customer can
 * edit. The running total the cashier sees is a preview, not an instruction.
 */

export interface CheckoutLine {
  productId: string;
  quantity: number;
}

export async function completeSale(input: {
  lines: CheckoutLine[];
  discountPercent: number;
  tender: TenderMethod;
  amountTendered?: number;
  terminalName: string;
  /**
   * Generated by the till before it posts, so a retry after a network timeout
   * returns the original sale instead of charging the customer twice.
   */
  idempotencyKey: string;
}): Promise<CheckoutResult> {
  try {
    const sale = await apiFetch<CompletedSale>("/api/v1/pos/sales", {
      method: "POST",
      body: {
        // No cashier is sent. The backend takes who rang this up from the
        // verified session, so a till cannot attribute a sale to somebody else.
        lines: input.lines,
        discountPercent: input.discountPercent,
        tender: input.tender,
        amountTendered: input.amountTendered,
        terminalName: input.terminalName,
        idempotencyKey: input.idempotencyKey,
      },
    });

    // The catalogue the page rendered with now has stale stock levels, since
    // this sale just took some off the shelf.
    revalidatePath(routes.cashierPos);

    return { success: true, sale };
  } catch (error) {
    // A failed sale must render a message the cashier can act on, not a crashed
    // page with a customer waiting at the counter.
    if (error instanceof ApiError) {
      return { success: false, message: error.message };
    }
    return { success: false, message: errorMessages.unexpected };
  }
}
